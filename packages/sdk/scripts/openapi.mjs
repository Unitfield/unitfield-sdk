#!/usr/bin/env node
// OpenAPI -> SDK types, one command.
//
//   node scripts/openapi.mjs all            sync snapshots from the running API, then generate types
//   node scripts/openapi.mjs sync           refresh openapi/*.json only
//   node scripts/openapi.mjs generate       regenerate src/generated/*.ts from the committed snapshots
//   node scripts/openapi.mjs check          fail when src/generated/*.ts does not match the snapshots
//
// Options: --api <base url>   API serving /openapi/{document}.json (default $UNITFIELD_API_URL or http://127.0.0.1:4750)
//          --from <directory> read {document}.json files exported by the Host instead of fetching
//
// The checked-in snapshots are filtered (paths by prefix, then the transitive closure of the components they
// reference) and deterministic, so a regeneration only produces a diff when the API contract changed.
import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const snapshotDir = join(root, "openapi");
const generatedDir = join(root, "src", "generated");
const HEADER = `/**\n * Generated by scripts/openapi.mjs from openapi/{name}.json. Do not edit; run \`pnpm gen:api\`.\n */\n\n`;
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

const [command = "all", ...rest] = process.argv.slice(2);
const options = parseOptions(rest);

const { sources } = JSON.parse(await readFile(join(snapshotDir, "sources.json"), "utf8"));

try {
  if (command === "sync" || command === "all") await sync();
  if (command === "generate" || command === "all") await generate({ check: false });
  if (command === "check") await generate({ check: true });
  if (!["sync", "generate", "all", "check"].includes(command)) fail(`Unknown command "${command}".`);
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}

function parseOptions(args) {
  const parsed = {};
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === "--api" || arg === "--from") {
      const value = args[++index];
      if (!value) fail(`${arg} needs a value.`);
      parsed[arg.slice(2)] = value;
    } else if (arg !== "--") fail(`Unknown option "${arg}".`);
  }
  return parsed;
}

function fail(message) {
  console.error(`openapi: ${message}`);
  process.exit(1);
}

async function sync() {
  const api = (options.api ?? process.env.UNITFIELD_API_URL ?? "http://127.0.0.1:4750").replace(/\/+$/, "");
  const documents = new Map();
  const load = async (name) => {
    if (!documents.has(name)) documents.set(name, options.from ? await readExport(name) : await fetchDocument(api, name));
    return documents.get(name);
  };

  for (const source of sources) {
    const document = await load(source.document);
    const file = join(snapshotDir, `${source.name}.json`);
    if (!document) {
      if (!source.optional) throw new Error(`Required document "${source.document}" is not available${options.from ? ` in ${options.from}` : ` at ${api}`}.`);
      console.log(`openapi: ${source.name}: "${source.document}" is not served yet, skipped${existsSync(file) ? " (keeping the committed snapshot)" : ""}.`);
      continue;
    }
    const slice = extract(document, source);
    const pathCount = Object.keys(slice.paths).length;
    if (pathCount === 0) {
      if (!source.optional) throw new Error(`"${source.document}" has no path under ${source.include.join(", ")}.`);
      console.log(`openapi: ${source.name}: no matching paths, skipped.`);
      continue;
    }
    await writeFile(file, `${JSON.stringify(slice, null, 2)}\n`);
    console.log(`openapi: ${source.name}: ${pathCount} paths, ${Object.keys(slice.components?.schemas ?? {}).length} schemas -> openapi/${source.name}.json`);
  }
}

async function readExport(name) {
  const file = join(resolve(options.from), `${name}.json`);
  return existsSync(file) ? JSON.parse(await readFile(file, "utf8")) : null;
}

async function fetchDocument(api, name) {
  const response = await fetch(`${api}/openapi/${name}.json`, { signal: AbortSignal.timeout(60_000) });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`GET ${api}/openapi/${name}.json failed with HTTP ${response.status}.`);
  return response.json();
}

/** Keep the paths under `include`, then only the components reachable from them. Output is key-sorted for stable diffs. */
// Snapshots are synced from whichever API runs locally, so its OAuth endpoints name a development authority. The committed
// snapshots always name the public one.
function publicSecuritySchemes(schemes) {
  const authority = "https://auth.unitfield.com";
  const urlKeys = new Set(["authorizationUrl", "tokenUrl", "refreshUrl", "openIdConnectUrl"]);
  return JSON.parse(JSON.stringify(schemes), (key, value) =>
    urlKeys.has(key) && typeof value === "string" ? authority + new URL(value).pathname : value);
}

function extract(document, source) {
  const paths = {};
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    if (source.include.some((prefix) => path.startsWith(prefix)) && !(source.exclude ?? []).some((prefix) => path.startsWith(prefix))) {
      paths[path] = item;
    }
  }

  const kept = new Map(); // section -> Set(name)
  const queue = [paths];
  const components = document.components ?? {};
  while (queue.length) {
    for (const ref of collectRefs(queue.pop())) {
      const match = /^#\/components\/([^/]+)\/(.+)$/.exec(ref);
      if (!match) throw new Error(`Unsupported $ref "${ref}".`);
      const [, section, rawName] = match;
      const name = rawName.replaceAll("~1", "/").replaceAll("~0", "~");
      if (!kept.has(section)) kept.set(section, new Set());
      if (kept.get(section).has(name)) continue;
      const target = components[section]?.[name];
      if (target === undefined) throw new Error(`Dangling $ref ${ref}.`);
      kept.get(section).add(name);
      queue.push(target);
    }
  }

  const slimComponents = {};
  for (const section of [...kept.keys()].sort()) {
    slimComponents[section] = Object.fromEntries([...kept.get(section)].sort().map((name) => [name, components[section][name]]));
  }
  if (components.securitySchemes) slimComponents.securitySchemes = publicSecuritySchemes(components.securitySchemes);

  const tagNames = new Set();
  for (const item of Object.values(paths)) {
    for (const method of METHODS) for (const tag of item[method]?.tags ?? []) tagNames.add(tag);
  }
  const output = { openapi: document.openapi, info: document.info };
  if (document.servers) output.servers = document.servers;
  output.paths = Object.fromEntries(Object.entries(paths).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  output.components = slimComponents;
  if (document.security) output.security = document.security;
  const tags = (document.tags ?? []).filter((tag) => tagNames.has(tag.name));
  if (tags.length) output.tags = tags;
  return output;
}

/** The snapshots keep examples and every `x-unitfield-*` extension (the contract tests read them). The generated types
 * drop both: examples only bloat the declaration files, and openapi-typescript mis-reads the `allOf` inside
 * `x-unitfield-permission-groups` as a schema. */
function prepareForTypes(document) {
  for (const item of Object.values(document.paths ?? {})) {
    for (const key of Object.keys(item)) if (key.startsWith("x-")) delete item[key];
    for (const method of METHODS) {
      const operation = item[method];
      if (operation) for (const key of Object.keys(operation)) if (key.startsWith("x-")) delete operation[key];
    }
  }
  return withoutExamples(document);
}

function withoutExamples(node, insidePropertyMap = false) {
  if (Array.isArray(node)) return node.map((item) => withoutExamples(item));
  if (!node || typeof node !== "object") return node;
  const result = {};
  for (const [key, value] of Object.entries(node)) {
    // Inside a `properties` map the keys are property names, so a property called "example" must survive.
    if (!insidePropertyMap && (key === "example" || key === "examples")) continue;
    result[key] = withoutExamples(value, !insidePropertyMap && key === "properties");
  }
  return result;
}

function collectRefs(node, found = new Set()) {
  if (Array.isArray(node)) for (const item of node) collectRefs(item, found);
  else if (node && typeof node === "object") {
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && typeof value === "string") found.add(value);
      else collectRefs(value, found);
    }
  }
  return found;
}

async function generate({ check }) {
  await mkdir(generatedDir, { recursive: true });
  const expected = new Set();
  let drift = 0;
  for (const source of sources) {
    const snapshot = join(snapshotDir, `${source.name}.json`);
    const output = join(generatedDir, `${source.name}.ts`);
    if (!existsSync(snapshot)) {
      if (!source.optional) throw new Error(`Missing snapshot openapi/${source.name}.json; run the sync first.`);
      continue;
    }
    expected.add(`${source.name}.ts`);
    const document = prepareForTypes(JSON.parse(await readFile(snapshot, "utf8")));
    const ast = await openapiTS(document, { alphabetize: true, emptyObjectsUnknown: true });
    const contents = `${HEADER.replace("{name}", source.name)}${astToString(ast)}`;
    if (check) {
      const current = existsSync(output) ? await readFile(output, "utf8") : null;
      if (current !== contents) {
        drift++;
        console.error(`openapi: src/generated/${source.name}.ts is out of date.`);
      }
    } else {
      await writeFile(output, contents);
      console.log(`openapi: src/generated/${source.name}.ts`);
    }
  }
  if (check && drift) throw new Error(`${drift} generated file(s) differ from the snapshots; run \`pnpm gen:api\`.`);
  if (check) console.log("openapi: generated types match the snapshots.");
  if (!check) {
    // A source that disappears from sources.json must not leave stale generated types behind.
    const { readdir } = await import("node:fs/promises");
    for (const file of await readdir(generatedDir)) {
      if (file.endsWith(".ts") && !expected.has(file)) await rm(join(generatedDir, file));
    }
  }
}
