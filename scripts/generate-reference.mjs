#!/usr/bin/env node
// Writes docs/reference/index.mdx from the committed OpenAPI snapshots (packages/sdk/openapi/*.json).
//
//   node scripts/generate-reference.mjs           write the file
//   node scripts/generate-reference.mjs --check   fail when the file is not what the snapshots produce
//
// The output is deterministic, so a regeneration only changes the file when the API contract changed.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const snapshotDir = join(root, "packages", "sdk", "openapi");
const target = join(root, "docs", "reference", "index.mdx");
const METHODS = ["get", "put", "post", "patch", "delete"];

// What the public reference leaves out is one shared file, scripts/public-api-filter.json, which the developer site reads too. The snapshots
// hold every operation the SDK is generated from; this index and the site list the public ones.
const FILTER = JSON.parse(await readFile(join(root, "scripts", "public-api-filter.json"), "utf8"));
const isDenied = (path, operation) =>
  FILTER.deny.some((rule) => rule.pathPrefixes.some((prefix) => path.startsWith(prefix)) || (operation.tags ?? []).some((tag) => rule.tags.includes(tag)));

// Editorial text per surface: who calls it, how, and which SDK client wraps it. The operations themselves come from the snapshots.
const SURFACES = [
  {
    name: "storefront",
    title: "Storefront API",
    summary: "Public reads of your site and homes, and the inquiry endpoint. Send your publishable key in `X-Unitfield-Key`. Requests that carry an `Origin` must come from an origin allowed on the key. SDK: `StorefrontClient`.",
  },
  {
    name: "customer",
    title: "Customer API",
    summary: "What a signed-in customer does: rental applications and the resident documents they accept. Bearer customer access token (from the customer sign-in). The organization comes from the token. SDK: `ApplicantClient`.",
  },
  {
    name: "resident",
    title: "Resident API",
    summary: "A resident's own leases, payments, requests and profile. Bearer token of a signed-in customer or resident. SDK: `ResidentClient`.",
  },
  {
    name: "apps",
    title: "Installed apps API",
    summary: "What an installed app calls with its client credentials, within the scopes its installation was granted. SDK: `AppsClient`.",
  },
  {
    name: "platform",
    title: "App management API",
    summary: "Catalog, installations, grants and webhook subscriptions. These need a signed-in Unitfield staff user; an installed app's token cannot call them. SDK: `PlatformClient`.",
  },
];

/** Prose is MDX: braces and angle brackets must not reach it as markup. */
function prose(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\|/g, "\\|")
    .replace(/[{}]/g, (character) => `\\${character}`)
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

async function build() {
  const out = [];
  out.push(`---
title: API reference
description: The public operations of the Unitfield APIs, from the OpenAPI documents the SDK is generated from.
order: 10
---

{/* Generated by scripts/generate-reference.mjs from packages/sdk/openapi/*.json. Do not edit; run "pnpm docs:reference". */}

This is an index of the public operations in the OpenAPI snapshots committed beside the SDK (\`packages/sdk/openapi\`). The SDK's types
are generated from the same files, and its contract tests check every call against them, so an operation listed here is what
the SDK can call. Operations that only Unitfield's own servers call are not listed. Request and response shapes are in the JSON files
and in the SDK's types (\`StorefrontPaths\`, \`CustomerPaths\`, \`ResidentPaths\`, \`AppsPaths\` and \`PlatformPaths\`, with matching
\`...Components\` and \`...Operations\`). The [developer site](https://developers.unitfield.com/reference) renders each operation in full.

The API root is \`https://api.unitfield.com\`.
`);
  let total = 0;
  for (const surface of SURFACES) {
    const document = JSON.parse(await readFile(join(snapshotDir, `${surface.name}.json`), "utf8"));
    const rows = [];
    for (const [path, item] of Object.entries(document.paths ?? {})) {
      for (const method of METHODS) {
        const operation = item[method];
        if (!operation || isDenied(path, operation)) continue;
        rows.push({ method: method.toUpperCase(), path, id: operation.operationId ?? "", summary: operation.summary ?? "", deprecated: operation.deprecated === true });
      }
    }
    rows.sort((a, b) => (a.path === b.path ? METHODS.indexOf(a.method.toLowerCase()) - METHODS.indexOf(b.method.toLowerCase()) : a.path < b.path ? -1 : 1));
    total += rows.length;
    out.push(`## ${surface.title}\n`);
    out.push(`${surface.summary}\n`);
    out.push(`Source: \`packages/sdk/openapi/${surface.name}.json\`. ${rows.length} operation${rows.length === 1 ? "" : "s"}.\n`);
    out.push("| Method | Path | Operation | Summary |\n| --- | --- | --- | --- |");
    for (const row of rows) out.push(`| ${row.method} | \`${row.path}\` | \`${row.id}\` | ${prose(row.summary)}${row.deprecated ? " (deprecated)" : ""} |`);
    out.push("");
  }
  out.push(`${total} operations in ${SURFACES.length} documents.\n`);
  return out.join("\n");
}

const content = await build();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch {
    /* missing */
  }
  if (current !== content) {
    console.error('docs/reference/index.mdx is out of date. Run "pnpm docs:reference" and commit the result.');
    process.exit(1);
  }
  console.log("docs/reference/index.mdx is up to date.");
} else {
  await writeFile(target, content);
  console.log(`Wrote ${target}`);
}
